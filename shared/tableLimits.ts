/**
 * 表格视图的规模约束 —— main 与 renderer 共用。
 *
 * 为什么不放 csv.ts：那是 CSV **格式**内核（解析 / 序列化 / 编码探测 / 规范判定），
 * 而行数上限是**产品策略**（PRD「不做大数据」）——一份 100 万行的 CSV 在格式上完全合法，
 * 只是我们的表格视图不加载它。让解析器知道视图上限会让两者的边界糊掉。
 *
 * 为什么不留在 main：渲染层粘贴扩表要拿它做护栏，而 tsconfig.web 的 include
 * 只有 src/ 与 shared/，主进程常量 import 不到。
 */

/** 表格视图能加载的最大数据行数（**不含表头**）；超限只回前 1,000 行只读预览。 */
export const ROW_LIMIT = 100_000;

/** 超限只读预览保留的数据行数（openCsv 与 xlsx 预览共用同一产品口径）。 */
export const PREVIEW_ROWS = 1_000;
